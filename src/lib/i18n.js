import { localizeDigits } from './digits.js';

export function fmt(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => {
    if (!(k in vars)) return m;
    const v = vars[k];
    return typeof v === 'number' ? localizeDigits(String(v)) : String(v);
  });
}

