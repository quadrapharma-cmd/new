"""Writes the trade dictionary and the text rules (W-06) for the database and the browser from tools/trade/terms.tsv:
  supabase/migrations/0071_trade_terms.sql   trade_norm() / trade_tokens() / trade_root() / trade_key() / trade_search_text() + the dictionary
  web/src/trade_terms.js                     window.dxTradeText: the same rules in the browser (demo search, paste parser, demo matching)
Run: python3 tools/trade/gen_terms.py [--check]   (--check: exit 1 when a generated file differs from what this script writes)
The two implementations are compared on a corpus by tools/trade/norm_parity.py (run by the trade SQL suite).
0071 is not applied anywhere yet; once it is, a change to the rules goes into a NEW migration written by this script."""
import os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'tools/trade/terms.tsv')
SQL = os.path.join(ROOT, 'supabase/migrations/0071_trade_terms.sql')
JS = os.path.join(ROOT, 'web/src/trade_terms.js')
KINDS = ('form', 'unit', 'strength', 'market', 'drug', 'cat')

def load():
    rows, seen = [], {}
    for n, line in enumerate(open(SRC, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'): continue
        k, canon, variants = line.split('\t')
        assert k in KINDS, 'line %d: unknown kind %s' % (n, k)
        assert canon == canon.lower() and ' ' not in canon, 'line %d: canonical words are one lower-case word' % n
        vs = [v.strip() for v in variants.split('|') if v.strip()]
        if canon not in vs: vs.insert(0, canon)
        assert all(len(v.split()) <= 2 for v in vs), 'line %d: a variant is one or two words' % n
        assert canon not in seen, 'line %d: %s twice' % (n, canon)
        seen[canon] = k; rows.append((k, canon, vs))
    return rows

def q(s): return "'" + s.replace("'", "''") + "'"

SQL_HEAD = r"""-- ═════════════════════════════════════════════════════════════════════
-- 0071 — trade words (W-06): one dictionary and one set of text rules for search and matching
--   GENERATED by tools/trade/gen_terms.py from tools/trade/terms.tsv — do not edit by hand (the browser copy,
--   web/src/trade_terms.js, is written from the same file; tools/trade/norm_parity.py compares the two on a corpus).
--   trade_norm(text)        lower case (A-Z), Arabic letters unified (أإآٱ→ا ة→ه ى→ي ؤ→و ئ→ي ک→ك ی→ي), harakat and tatweel
--                           removed, Arabic-Indic / Persian digits → 0-9, a number split from the letters it touches,
--                           everything but letters, digits, a decimal point between digits and % after a digit → space
--   trade_tokens(text)      the canonical words: a one- or two-word variant → its canonical word; a number followed by a
--                           strength unit → one word (500 mg, ٥٠٠ ملجم → 500mg)
--   trade_root(text)        the words that name the item (no form, unit, strength, number or trade word), sorted, one space
--   trade_key(text)         root + strength + form: the item as the trade names it ("panadol 500mg tab")
--   trade_search_text(text) ' ' || the written words and their canonical words || ' ' — market_search matches each canonical query
--                           word at the start of a word of it
--   trade_terms             the dictionary (Drugbox moderators add words with trade_term_add)
-- Not handled on purpose (owner, W-06): Franco-Arabic, and «باتش».
-- Safe to run twice.
-- ═════════════════════════════════════════════════════════════════════

create table if not exists public.trade_terms (
  term       text primary key,
  canon      text not null,
  kind       text not null check (kind in ('form', 'unit', 'strength', 'market', 'drug', 'cat')),
  added_by   uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint trade_terms_len check (length(term) between 1 and 60 and length(canon) between 1 and 40 and canon ~ '^[0-9a-z]+$'));
create index if not exists idx_trade_terms_canon on public.trade_terms (canon);
create index if not exists idx_trade_terms_added_by on public.trade_terms (added_by) where added_by is not null;
alter table public.trade_terms enable row level security;
do $$ begin
  create policy "trade terms: members read" on public.trade_terms for select to authenticated using (true);
exception when duplicate_object then null; end $$;
revoke all on public.trade_terms from public, anon, authenticated;
grant select on public.trade_terms to anon, authenticated;   -- anon: answers with nothing (the policy is for members), never an error
grant all on public.trade_terms to service_role;

create or replace function public.trade_norm(p text) returns text language sql immutable parallel safe set search_path = public as $$
  select btrim(regexp_replace(
    regexp_replace(regexp_replace(regexp_replace(
      regexp_replace(regexp_replace(
        regexp_replace(
          translate(coalesce(p, ''),
            'ABCDEFGHIJKLMNOPQRSTUVWXYZ٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹٫أإآٱةىؤئکی',
            'abcdefghijklmnopqrstuvwxyz01234567890123456789.ااااهيويكي'),
          '[\u0640\u064B-\u065F\u0670\u06D6-\u06ED]', '', 'g'),                                   -- tatweel, harakat, Quranic marks
        '([0-9])([a-z\u0621-\u064A])', '\1 \2', 'g'), '([a-z\u0621-\u064A])([0-9])', '\1 \2', 'g'),
      '[^0-9a-z.%\u0621-\u064A]+', ' ', 'g'),                                           -- every other character is a space
      '(?<![0-9])\.|\.(?![0-9])', ' ', 'g'), '(?<![0-9])%', ' ', 'g'),
    '\s+', ' ', 'g'))
$$;

create or replace function public.trade_tokens(p text) returns text[] language plpgsql stable parallel safe set search_path = public as $$
declare t text[] := string_to_array(nullif(public.trade_norm(p), ''), ' '); n int := coalesce(array_length(t, 1), 0); i int := 1;
        out text[] := '{}'; c text; u text; adv int;
begin
  while i <= n loop
    -- a number and the strength unit after it (one or two words)
    if t[i] ~ '^[0-9]+(\.[0-9]+)?$' and i < n then
      u := null; adv := 0;
      if i + 1 < n then select tt.canon into u from public.trade_terms tt where tt.term = t[i+1] || ' ' || t[i+2] and tt.kind = 'strength'; if u is not null then adv := 3; end if; end if;
      if u is null then select tt.canon into u from public.trade_terms tt where tt.term = t[i+1] and tt.kind = 'strength'; if u is not null then adv := 2; end if; end if;
      if u is not null then out := out || (regexp_replace(t[i], '\.0+$', '') || u); i := i + adv; continue; end if;
    end if;
    c := null;
    if i < n then select tt.canon into c from public.trade_terms tt where tt.term = t[i] || ' ' || t[i+1]; end if;
    if c is not null then out := out || c; i := i + 2; continue; end if;
    select tt.canon into c from public.trade_terms tt where tt.term = t[i];
    out := out || coalesce(c, t[i]); i := i + 1;
  end loop;
  return out;
end $$;

-- the kind of a canonical word (null: not in the dictionary — a word that names the item)
create or replace function public.trade_kind(p_word text) returns text language sql stable parallel safe set search_path = public as $$
  select tt.kind from public.trade_terms tt where tt.term = p_word and tt.canon = p_word limit 1
$$;

create or replace function public.trade_root(p text) returns text language sql stable parallel safe set search_path = public as $$
  select coalesce(string_agg(w, ' ' order by w), '') from (
    select distinct w from unnest(public.trade_tokens(p)) w
     where length(w) > 1 and w !~ '^[0-9.%]+' and coalesce(public.trade_kind(w), 'drug') = 'drug') x
$$;

create or replace function public.trade_key(p text) returns text language sql stable parallel safe set search_path = public as $$
  select btrim(public.trade_root(p) || ' ' || coalesce((select string_agg(w, ' ' order by w) from (
    select distinct w from unnest(public.trade_tokens(p)) w
     where w ~ '^[0-9.]+(mg|mcg|g|ml|iu)$' or public.trade_kind(w) = 'form') x), ''))
$$;

create or replace function public.trade_search_text(p text) returns text language sql stable parallel safe set search_path = public as $$
  select ' ' || coalesce((select string_agg(w, ' ' order by o) from (      -- each word once, where it first appears
    select w, min(o) o from unnest(string_to_array(nullif(public.trade_norm(p), ''), ' ') || public.trade_tokens(p)) with ordinality as u(w, o) where w <> '' group by w) x), '') || ' '
$$;

-- a member's query as LIKE patterns: every canonical word must begin a word of search_text
create or replace function public.trade_query_patterns(p text) returns text[] language sql stable parallel safe set search_path = public as $$
  select coalesce(array_agg(distinct '% ' || replace(replace(replace(w, '\', '\\'), '%', '\%'), '_', '\_') || '%'), '{}')
    from unnest(public.trade_tokens(left(coalesce(p, ''), 100))) w where w <> '' and coalesce(public.trade_kind(w), '') <> 'market'
$$;

revoke all on function public.trade_norm(text), public.trade_tokens(text), public.trade_kind(text), public.trade_root(text), public.trade_key(text),
  public.trade_search_text(text), public.trade_query_patterns(text) from public, anon;
grant execute on function public.trade_norm(text), public.trade_tokens(text), public.trade_kind(text), public.trade_root(text), public.trade_key(text),
  public.trade_search_text(text), public.trade_query_patterns(text) to authenticated, service_role;

-- Drugbox moderators add a word (both spellings reach the same canonical word)
create or replace function public.trade_term_add(p_term text, p_canon text, p_kind text default 'drug') returns text language plpgsql security definer set search_path = public as $$
declare t text := public.trade_norm(p_term); c text := lower(btrim(coalesce(p_canon, '')));
begin
  if auth.uid() is null or not public.is_moderator() then raise exception 'Only the Drugbox team can add trade words' using errcode = '42501'; end if;
  if t = '' or length(t) > 60 or array_length(string_to_array(t, ' '), 1) > 2 then raise exception 'A word or two, up to 60 letters' using errcode = '22023'; end if;
  if c !~ '^[0-9a-z]{1,40}$' then raise exception 'The canonical word is one English word (a-z, 0-9)' using errcode = '22023'; end if;
  if p_kind not in ('form', 'unit', 'strength', 'market', 'drug', 'cat') then raise exception 'Unknown kind' using errcode = '22023'; end if;
  insert into public.trade_terms (term, canon, kind, added_by) values (c, c, p_kind, auth.uid()) on conflict (term) do nothing;
  insert into public.trade_terms (term, canon, kind, added_by) values (t, c, p_kind, auth.uid())
    on conflict (term) do update set canon = excluded.canon, kind = excluded.kind, added_by = excluded.added_by;
  return c;
end $$;
revoke all on function public.trade_term_add(text, text, text) from public, anon, authenticated, service_role;
grant execute on function public.trade_term_add(text, text, text) to authenticated, service_role;

-- ── the dictionary (from tools/trade/terms.tsv) ────
"""

SQL_TAIL = """
notify pgrst, 'reload schema';
"""

JS_RULES = r"""
  /* the same rules as the database's trade_norm / trade_tokens / trade_root / trade_key / trade_search_text (0071) */
  var FROM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹٫أإآٱةىؤئکی', TO = 'abcdefghijklmnopqrstuvwxyz01234567890123456789.ااااهيويكي', MAP = {};
  for (var i = 0; i < FROM.length; i++) MAP[FROM[i]] = TO[i];
  function norm(s) {
    s = String(s == null ? '' : s).replace(/[A-Z٠-٩۰-۹٫أإآٱةىؤئکی]/g, function (c) { return MAP[c]; });
    s = s.replace(/[ـً-ٰٟۖ-ۭ]/g, '');
    s = s.replace(/([0-9])([a-zء-ي])/g, '$1 $2').replace(/([a-zء-ي])([0-9])/g, '$1 $2');
    s = s.replace(/[^0-9a-z.%ء-ي]+/g, ' ');
    s = s.replace(/(?<![0-9])\.|\.(?![0-9])/g, ' ').replace(/(?<![0-9])%/g, ' ');
    return s.replace(/\s+/g, ' ').trim();
  }
  var TERM = {}, KIND = {};
  T.forEach(function (r) { var k = r[0], c = r[1]; KIND[c] = k; r[2].forEach(function (v) { var n = norm(v); if (n && !(n in TERM)) TERM[n] = { c: c, k: k }; }); TERM[c] = { c: c, k: k }; });
  function tokens(s) {
    var t = norm(s); t = t ? t.split(' ') : []; var n = t.length, out = [], i = 0, u;
    while (i < n) {
      if (/^[0-9]+(\.[0-9]+)?$/.test(t[i]) && i < n - 1) {
        var adv = 0; u = null;
        if (i < n - 2) { u = TERM[t[i + 1] + ' ' + t[i + 2]]; if (u && u.k === 'strength') adv = 3; else u = null; }
        if (!u) { u = TERM[t[i + 1]]; if (u && u.k === 'strength') adv = 2; else u = null; }
        if (u) { out.push(t[i].replace(/\.0+$/, '') + u.c); i += adv; continue; }
      }
      if (i < n - 1 && TERM[t[i] + ' ' + t[i + 1]]) { out.push(TERM[t[i] + ' ' + t[i + 1]].c); i += 2; continue; }
      out.push(TERM[t[i]] ? TERM[t[i]].c : t[i]); i++;
    }
    return out;
  }
  function kind(w) { return KIND[w] || null; }
  function uniqSorted(a) { var o = {}; a.forEach(function (x) { o[x] = 1; }); return Object.keys(o).sort(function (x, y) { return x < y ? -1 : x > y ? 1 : 0; }); }
  function root(s) { return uniqSorted(tokens(s).filter(function (w) { return w.length > 1 && !/^[0-9.%]+/.test(w) && (kind(w) || 'drug') === 'drug'; })).join(' '); }
  function key(s) { var r = root(s), x = uniqSorted(tokens(s).filter(function (w) { return /^[0-9.]+(mg|mcg|g|ml|iu)$/.test(w) || kind(w) === 'form'; })).join(' ');
    return (r + ' ' + x).trim(); }
  function searchText(s) { var n = norm(s), all = (n ? n.split(' ') : []).concat(tokens(s)), seen = {}, out = [];
    all.forEach(function (w) { if (w && !seen[w]) { seen[w] = 1; out.push(w); } }); return ' ' + out.join(' ') + ' '; }
  /* a query matches when each canonical word (trade words aside) begins a word of the text */
  function matches(text, q) { var st = searchText(text), ws = tokens(String(q || '').slice(0, 100)).filter(function (w) { return kind(w) !== 'market'; });
    return ws.every(function (w) { return st.indexOf(' ' + w) >= 0; }); }
  window.dxTradeText = { norm: norm, tokens: tokens, kind: kind, root: root, key: key, searchText: searchText, matches: matches, terms: T };
"""

def gen():
    rows = load()
    vals = []
    for k, canon, vs in rows:
        for v in vs: vals.append('(%s, %s, %s)' % (q(v), q(canon), q(k)))
    sql = SQL_HEAD + 'insert into public.trade_terms (term, canon, kind)\nselect distinct on (public.trade_norm(v.t)) public.trade_norm(v.t), v.c, v.k from (values\n  ' + ',\n  '.join(vals) + \
        ') v(t, c, k) where public.trade_norm(v.t) <> \'\'\non conflict (term) do update set canon = excluded.canon, kind = excluded.kind where public.trade_terms.added_by is null;\n' + SQL_TAIL
    js = ('/* GENERATED by tools/trade/gen_terms.py from tools/trade/terms.tsv — do not edit by hand.\n'
          '   Trade words and text rules (W-06) for the browser: the demo\'s search and matching, the paste parser (W-14). */\n(function () {\n'
          '  var T = ' + json.dumps([[k, c, vs] for k, c, vs in rows], ensure_ascii=False) + ';\n' + JS_RULES + '})();\n')
    return sql, js

def main():
    sql, js = gen()
    if '--check' in sys.argv:
        bad = [p for p, s in ((SQL, sql), (JS, js)) if not os.path.exists(p) or open(p, encoding='utf-8').read() != s]
        print('trade terms: ' + ('out of date: ' + ', '.join(bad) if bad else 'OK')); sys.exit(1 if bad else 0)
    open(SQL, 'w', encoding='utf-8').write(sql); open(JS, 'w', encoding='utf-8').write(js)
    print('wrote', SQL, 'and', JS)

if __name__ == '__main__': main()
